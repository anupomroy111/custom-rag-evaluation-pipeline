def build():
    splits = {"development": [], "heldout": []}
    for fam, split, primary, context, cases in FAMILIES:
        for i, case in enumerate(cases, 1):
            mut, claim, expected, diff = case[:4]
            extra = case[4] if len(case) > 4 else None
            ctx = list(context) + ([extra] if extra else [])
            category = MUT_CATEGORY[mut] or primary
            answer = claim
            if mut == "citation_manipulation":
                answer = f"{claim} [id:p99]"
            splits[split].append({
                "id": f"{fam}-{i:02d}",
                "category": category,
                "difficulty": diff,
                "context": ctx,
                "generated_answer": answer,
                "claims": [claim],
                "expected_status": expected,
                "expected_reason": f"{mut} mutation of family {fam}",
                "probe_question": claim.rstrip(".") + "?",
                "scenario_family": fam,
                "mutation_type": mut,
                "pair_id": f"{fam}-base" if mut in ("supported_control",) else f"{fam}-{mut}",
                "provenance": "synthetic-author-reviewed",
            })
    for split, cases in splits.items():
        path = ROOT / "data" / split / ("dev_fixtures.json" if split == "development"
                                       else "heldout_fixtures.json")
        path.write_text(json.dumps({
            "description": f"V2.1 {split} fixtures; synthetic, author-reviewed; "
                           f"scenario families disjoint from the other split.",
            "provenance": "synthetic-author-reviewed",
            "cases": cases,
        }, ensure_ascii=False, indent=2), encoding="utf-8")
        print(split, len(cases))


if __name__ == "__main__":
    build()